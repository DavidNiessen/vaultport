//! Opt-in shell integration scripts.
//!
//! Each script makes an interactive shell emit `OSC 7` (working directory) and `OSC 133`
//! prompt/command marks (zsh and fish 3 also report the command line via `OSC 633 ; E`), which
//! [`crate::shell::ShellIntegrationParser`] understands. The scripts are:
//!
//! * **opt-in**: they do nothing unless `VAULTPORT_SHELL_INTEGRATION` is set (non-empty) in
//!   the remote environment, so sourcing them from a dotfile is harmless;
//! * **idempotent**: sourcing twice installs the hooks once;
//! * **small**: no external commands, no subshells per prompt.
//!
//! The app may inject one of them after login (e.g. by sending
//! `export VAULTPORT_SHELL_INTEGRATION=1; eval "$(…)"`) only with the user's consent.

use std::path::{Path, PathBuf};

/// Name of the environment variable that enables the scripts.
pub const ENABLE_VAR: &str = "VAULTPORT_SHELL_INTEGRATION";

/// Integration script for bash 4.4+ (uses `PROMPT_COMMAND`, `PS0` and `PS1`).
pub const BASH: &str = include_str!("../scripts/bash.sh");
/// Integration script for zsh 5.1+ (uses `precmd` / `preexec` hooks).
pub const ZSH: &str = include_str!("../scripts/zsh.zsh");
/// Integration script for fish 3.1+ (wraps `fish_prompt`, uses `fish_preexec` /
/// `fish_postexec` events).
pub const FISH: &str = include_str!("../scripts/fish.fish");

/// Shells with an integration script.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Shell {
    Bash,
    Zsh,
    Fish,
}

impl Shell {
    /// Guesses the shell from a login shell path or name such as `/usr/bin/zsh` or `-bash`.
    #[must_use]
    pub fn from_path(path: &str) -> Option<Self> {
        let name = path
            .rsplit('/')
            .next()
            .unwrap_or(path)
            .trim_start_matches('-');
        match name {
            "bash" => Some(Self::Bash),
            "zsh" => Some(Self::Zsh),
            "fish" => Some(Self::Fish),
            _ => None,
        }
    }

    /// The integration script for this shell.
    #[must_use]
    pub const fn script(self) -> &'static str {
        match self {
            Self::Bash => BASH,
            Self::Zsh => ZSH,
            Self::Fish => FISH,
        }
    }
}

/// How to start a local shell with the integration script loaded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LocalLaunch {
    /// Arguments for the shell program (they replace the usual `-l`).
    pub args: Vec<String>,
    /// Extra environment variables.
    pub env: Vec<(String, String)>,
    /// Files to write before starting the shell (path, contents).
    pub files: Vec<(PathBuf, String)>,
}

/// Quotes `s` for POSIX shells (bash, zsh).
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Quotes `s` for fish.
fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', r"\\").replace('\'', r"\'"))
}

const BASH_RC: &str = "\
# Generated by Vaultport: the startup files of a login shell, then shell integration.
if [ -r /etc/profile ]; then . /etc/profile; fi
for __sshc_f in ~/.bash_profile ~/.bash_login ~/.profile; do
  if [ -r \"$__sshc_f\" ]; then . \"$__sshc_f\"; break; fi
done
unset __sshc_f
";

/// Sources the user's zsh startup file `$1` with the user's `ZDOTDIR` in effect.
const ZSH_SOURCE_USER: &str = "\
__sshc_zd=$ZDOTDIR
ZDOTDIR=$SSHC_USER_ZDOTDIR
[[ -r $ZDOTDIR/FILE ]] && builtin source \"$ZDOTDIR/FILE\"
SSHC_USER_ZDOTDIR=$ZDOTDIR
ZDOTDIR=$__sshc_zd
";

/// Arguments, environment and files that start `shell` as an interactive login shell with
/// the integration script loaded, without the user editing their dotfiles.
///
/// * bash: `--rcfile` pointing at a file that reads the login startup files and the script;
/// * zsh: a temporary `ZDOTDIR` whose startup files source the user's own (from
///   `user_zdotdir`, else `$HOME`) and restore `ZDOTDIR` after `.zshrc`;
/// * fish: `--init-command`, which runs after the user's configuration.
///
/// All files are written to `dir`. `VAULTPORT_SHELL_INTEGRATION=1` is always set.
#[must_use]
pub fn local_launch(shell: Shell, dir: &Path, user_zdotdir: Option<&str>) -> LocalLaunch {
    let path = |name: &str| dir.join(name);
    let script = |name: &str| path(name).to_string_lossy().into_owned();
    let mut env = vec![(ENABLE_VAR.to_owned(), "1".to_owned())];
    let mut files = Vec::new();
    let args = match shell {
        Shell::Bash => {
            files.push((path("bash.sh"), BASH.to_owned()));
            let rc = format!("{BASH_RC}. {}\n", sh_quote(&script("bash.sh")));
            files.push((path("bashrc"), rc));
            vec!["--rcfile".to_owned(), script("bashrc"), "-i".to_owned()]
        }
        Shell::Zsh => {
            files.push((path("zsh.zsh"), ZSH.to_owned()));
            let user = |file: &str| ZSH_SOURCE_USER.replace("FILE", file);
            let zshenv = format!(
                "# Generated by Vaultport: loads your startup files, then shell integration.\n\
                 if [[ -n ${{SSHC_USER_ZDOTDIR-}} ]]; then __sshc_had_zd=1\n\
                 else __sshc_had_zd=; SSHC_USER_ZDOTDIR=$HOME; fi\n{}",
                user(".zshenv")
            );
            let zprofile = format!("# Generated by Vaultport.\n{}", user(".zprofile"));
            let zshrc = format!(
                "# Generated by Vaultport.\n{}\
                 if [[ -z $__sshc_had_zd && $SSHC_USER_ZDOTDIR == $HOME ]]; then unset ZDOTDIR\n\
                 else ZDOTDIR=$SSHC_USER_ZDOTDIR; fi\n\
                 unset SSHC_USER_ZDOTDIR __sshc_zd __sshc_had_zd\n\
                 builtin source {}\n",
                user(".zshrc"),
                sh_quote(&script("zsh.zsh"))
            );
            files.push((path(".zshenv"), zshenv));
            files.push((path(".zprofile"), zprofile));
            files.push((path(".zshrc"), zshrc));
            env.push(("ZDOTDIR".to_owned(), dir.to_string_lossy().into_owned()));
            if let Some(zd) = user_zdotdir.filter(|z| !z.is_empty()) {
                env.push(("SSHC_USER_ZDOTDIR".to_owned(), zd.to_owned()));
            }
            vec!["-l".to_owned()]
        }
        Shell::Fish => {
            files.push((path("fish.fish"), FISH.to_owned()));
            vec![
                "-l".to_owned(),
                "--init-command".to_owned(),
                format!("source {}", fish_quote(&script("fish.fish"))),
            ]
        }
    };
    LocalLaunch { args, env, files }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]
    use super::*;

    #[test]
    fn scripts_are_guarded_and_licensed() {
        for sh in [Shell::Bash, Shell::Zsh, Shell::Fish] {
            let s = sh.script();
            assert!(s.starts_with("# SPDX-License-Identifier: GPL-3.0-or-later\n"));
            assert!(s.contains(ENABLE_VAR));
            assert!(s.contains("__sshc_si"));
            assert!(s.contains("]7;file://"));
            assert!(s.contains("]133;A"));
            assert!(s.len() < 4096, "keep scripts small");
        }
    }

    #[test]
    fn shell_detection() {
        assert_eq!(Shell::from_path("/usr/bin/zsh"), Some(Shell::Zsh));
        assert_eq!(Shell::from_path("-bash"), Some(Shell::Bash));
        assert_eq!(Shell::from_path("fish"), Some(Shell::Fish));
        assert_eq!(Shell::from_path("/bin/sh"), None);
    }

    fn files(l: &LocalLaunch) -> Vec<String> {
        l.files
            .iter()
            .map(|(p, _)| p.file_name().unwrap().to_string_lossy().into_owned())
            .collect()
    }

    fn file<'a>(l: &'a LocalLaunch, name: &str) -> &'a str {
        &l.files
            .iter()
            .find(|(p, _)| p.file_name().unwrap() == name)
            .unwrap()
            .1
    }

    /// Whether `bin` is a shell that actually runs here. A launcher alone is not enough: on
    /// Windows `bash` may be the WSL stub, which starts but fails without a distribution.
    fn usable(bin: &str) -> bool {
        use std::process::{Command, Stdio};
        Command::new(bin)
            .args(["-c", "exit 0"])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|s| s.success())
    }

    /// `dir/name` the way [`local_launch`] spells it on this platform.
    fn joined(dir: &str, name: &str) -> String {
        Path::new(dir).join(name).to_string_lossy().into_owned()
    }

    #[test]
    fn local_launch_bash() {
        let l = local_launch(Shell::Bash, Path::new("/data/it's"), None);
        let rcfile = joined("/data/it's", "bashrc");
        assert_eq!(l.args, ["--rcfile", rcfile.as_str(), "-i"]);
        assert_eq!(l.env, [(ENABLE_VAR.to_owned(), "1".to_owned())]);
        assert_eq!(files(&l), ["bash.sh", "bashrc"]);
        let rc = file(&l, "bashrc");
        assert!(rc.contains("~/.bash_profile ~/.bash_login ~/.profile"));
        assert!(rc.ends_with(&format!(
            ". {}\n",
            sh_quote(&joined("/data/it's", "bash.sh"))
        )));
        assert_eq!(file(&l, "bash.sh"), BASH);
    }

    #[test]
    fn local_launch_zsh() {
        let l = local_launch(
            Shell::Zsh,
            Path::new("/data/si"),
            Some("/home/u/.config/zsh"),
        );
        assert_eq!(l.args, ["-l"]);
        assert!(
            l.env
                .contains(&("ZDOTDIR".to_owned(), "/data/si".to_owned()))
        );
        assert!(l.env.contains(&(
            "SSHC_USER_ZDOTDIR".to_owned(),
            "/home/u/.config/zsh".to_owned()
        )));
        assert_eq!(files(&l), ["zsh.zsh", ".zshenv", ".zprofile", ".zshrc"]);
        assert!(file(&l, ".zshenv").contains("builtin source \"$ZDOTDIR/.zshenv\""));
        assert!(file(&l, ".zprofile").contains("\"$ZDOTDIR/.zprofile\""));
        let rc = file(&l, ".zshrc");
        assert!(rc.contains("\"$ZDOTDIR/.zshrc\""));
        assert!(rc.contains("ZDOTDIR=$SSHC_USER_ZDOTDIR"));
        let source = format!(
            "builtin source {}\n",
            sh_quote(&joined("/data/si", "zsh.zsh"))
        );
        assert!(rc.ends_with(&source));
        let l = local_launch(Shell::Zsh, Path::new("/data/si"), None);
        assert!(l.env.iter().all(|(k, _)| k != "SSHC_USER_ZDOTDIR"));
    }

    #[test]
    fn local_launch_fish() {
        let l = local_launch(Shell::Fish, Path::new("/data/a\\b"), None);
        let init = format!("source {}", fish_quote(&joined("/data/a\\b", "fish.fish")));
        assert_eq!(l.args, ["-l", "--init-command", init.as_str()]);
        assert_eq!(files(&l), ["fish.fish"]);
    }

    /// Syntax-checks the generated startup files with locally installed shells, if any.
    #[test]
    fn local_launch_files_parse() {
        use std::process::{Command, Stdio};
        for (bin, sh) in [("bash", Shell::Bash), ("zsh", Shell::Zsh)] {
            if !usable(bin) {
                continue;
            }
            let l = local_launch(sh, Path::new("/tmp/sshc"), None);
            for (path, body) in &l.files {
                let Ok(out) = Command::new(bin)
                    .args(["-n", "-c", body])
                    .stdout(Stdio::null())
                    .output()
                else {
                    break;
                };
                assert!(
                    out.status.success(),
                    "{bin} {}: {}",
                    path.display(),
                    String::from_utf8_lossy(&out.stderr)
                );
            }
        }
    }

    /// Starts each installed shell through [`local_launch`] and checks that the user's own
    /// startup file was read and that the integration is active (bash and zsh print prompt
    /// marks even without a terminal; fish draws no prompt then, so check its guard variable).
    #[test]
    fn local_launch_shells_run() {
        use std::process::{Command, Stdio};
        let cases = [
            (Shell::Bash, ".profile", "export SSHC_T=yes\n", "\x1b]133;A"),
            (Shell::Zsh, ".zshrc", "export SSHC_T=yes\n", "\x1b]133;A"),
            (
                Shell::Fish,
                ".config/fish/config.fish",
                "set -gx SSHC_T yes\n",
                "si=1",
            ),
        ];
        for (sh, rc, body, mark) in cases {
            let bin = format!("{sh:?}").to_lowercase();
            if !usable(&bin) {
                continue;
            }
            let tmp = std::env::temp_dir().join(format!("sshc-si-{}-{bin}", std::process::id()));
            let (home, dir) = (tmp.join("home"), tmp.join("si"));
            std::fs::create_dir_all(home.join(rc).parent().unwrap()).unwrap();
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(home.join(rc), body).unwrap();
            let l = local_launch(sh, &dir, None);
            for (p, b) in &l.files {
                std::fs::write(p, b).unwrap();
            }
            // Without a terminal, zsh and fish need -i to run interactively.
            let mut args = l.args.clone();
            if sh != Shell::Bash {
                args.push("-i".to_owned());
            }
            let out = Command::new(&bin)
                .args(&args)
                .env_remove("ZDOTDIR")
                .envs(l.env.iter().map(|(k, v)| (k, v)))
                .env("HOME", &home)
                .env("XDG_CONFIG_HOME", home.join(".config"))
                .stdin(Stdio::piped())
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .spawn()
                .and_then(|mut c| {
                    use std::io::Write;
                    c.stdin
                        .take()
                        .unwrap()
                        .write_all(b"echo t=$SSHC_T si=$__sshc_si zd=\"$ZDOTDIR\".\nexit\n")?;
                    c.wait_with_output()
                });
            let _ = std::fs::remove_dir_all(&tmp);
            let Ok(out) = out else { continue };
            let all = format!(
                "{}{}",
                String::from_utf8_lossy(&out.stdout),
                String::from_utf8_lossy(&out.stderr)
            );
            assert!(all.contains("t=yes"), "{bin}: {all}");
            assert!(all.contains(mark), "{bin}: {all:?}");
            if sh == Shell::Zsh {
                assert!(all.contains("zd=."), "{bin}: ZDOTDIR not restored: {all}");
            }
        }
    }

    /// bash reports each recorded command line, escaped so the parser restores it exactly, and
    /// skips commands that bash leaves out of its history.
    #[test]
    fn bash_reports_command_lines() {
        use crate::{ShellEvent, ShellIntegrationParser};
        use std::io::Write;
        use std::process::{Command, Stdio};
        if !usable("bash") {
            return;
        }
        let tmp = std::env::temp_dir().join(format!("sshc-si-e-{}", std::process::id()));
        std::fs::create_dir_all(&tmp).unwrap();
        let script = tmp.join("bash.sh");
        std::fs::write(&script, BASH).unwrap();
        let rc = tmp.join("rc");
        std::fs::write(&rc, format!(". {}\n", sh_quote(&script.to_string_lossy()))).unwrap();
        let out = Command::new("bash")
            .args(["--rcfile", &rc.to_string_lossy(), "-i"])
            .env(ENABLE_VAR, "1")
            .env("HOME", &tmp)
            .env("HISTFILE", tmp.join("history"))
            .env("HISTCONTROL", "ignorespace")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .and_then(|mut c| {
                c.stdin
                    .take()
                    .unwrap()
                    .write_all(b"echo a; echo 'b\\c'\n echo hidden\necho again\nexit\n")?;
                c.wait_with_output()
            });
        let _ = std::fs::remove_dir_all(&tmp);
        let Ok(out) = out else { return };
        let mut parser = ShellIntegrationParser::new();
        let mut commands = Vec::new();
        for ev in parser.feed(&[out.stdout, out.stderr].concat()) {
            if let ShellEvent::CommandExecuted { command: Some(c) } = ev {
                commands.push(c);
            }
        }
        assert_eq!(commands, ["echo a; echo 'b\\c'", "echo again", "exit"]);
    }

    /// Syntax-checks the scripts with locally installed shells, if any.
    #[test]
    fn scripts_parse_with_installed_shells() {
        use std::io::Write;
        use std::process::{Command, Stdio};
        for (bin, script) in [("bash", BASH), ("zsh", ZSH), ("fish", FISH)] {
            if !usable(bin) {
                continue;
            }
            let Ok(mut child) = Command::new(bin)
                .arg("-n")
                .stdin(Stdio::piped())
                .stdout(Stdio::null())
                .stderr(Stdio::piped())
                .spawn()
            else {
                continue;
            };
            child
                .stdin
                .take()
                .unwrap()
                .write_all(script.as_bytes())
                .unwrap();
            let out = child.wait_with_output().unwrap();
            assert!(
                out.status.success(),
                "{bin}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
        }
    }
}
